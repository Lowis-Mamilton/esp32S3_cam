#!/usr/bin/env python3
"""Generate vectors.h from docs/protocol-vectors.json.

Usage: gen_vectors.py <in.json> <out.h>
"""
import json
import sys


def c(s):
    return '"' + s + '"'


def cstr(s):
    """C string literal using octal escapes for every non-printable / non-ASCII UTF-8 byte."""
    safe = lambda b: 0x20 <= b < 0x7F and chr(b) not in ('"', "\\")
    return '"' + "".join(chr(b) if safe(b) else "\\%03o" % b for b in s.encode("utf-8")) + '"'


# Line extra (protocol.md 9): six i16 fields, then flags u8 and reserved u8.
LINE_I16 = ("angle_cdeg", "offset_x", "x0", "y0", "x1", "y1")


def emit_payloads(v, o):
    """Typed C constants for the decoded expectations. Needs mxcam_proto.h included first."""
    pl = v["payloads"]
    for name in ("results_color_two", "results_tag_one", "results_line_one"):
        p = pl[name]
        recs = []
        for r in p["results"]:
            extra = []
            if "extra" in r:
                e = r["extra"]
                vals = [e["rotation_cdeg"]] + [n for c in e["corners"] for n in c]
                for n in vals:
                    n &= 0xFFFF
                    extra += [n & 0xFF, n >> 8]
            if "line" in r:
                e = r["line"]
                for k in LINE_I16:
                    n = e[k] & 0xFFFF
                    extra += [n & 0xFF, n >> 8]
                extra += [e["flags"], 0]  # flags, reserved
            recs.append("{%d, %d, %d, %d, %d, %d, %d, {%s}}" % (
                r["id"], r["x"], r["y"], r["width"], r["height"], r["confidence"], len(extra),
                ", ".join(str(b) for b in extra) or "0"))
        o.append("static const mxp_results_t VEC_P_%s = {%d, %d, %d, {%s}};" % (
            name.upper(), p["frame_id"], p["function_id"], len(recs), ", ".join(recs)))
    c = pl["config_default"]
    o.append("static const mxp_config_t VEC_P_CONFIG_DEFAULT = {%d, %d, %d, %d, %d, %d, %d, %du, %d, %d, %d};" % (
        c["tolerance"], c["min_area"], c["color_max_results"], c["color_show_names"], c["tag_show_names"],
        c["face_threshold"], c["face_max_results"], c["uart_baud"], c["i2c_address"], c["led_brightness"], c["dirty"]))
    for name in ("learn_request", "learn_request_with_id"):
        l = pl[name]
        o.append("static const mxp_learn_req_t VEC_P_%s = {%d, %d, %d, %d, %d, %d, %d};" % (
            name.upper(), l["function_id"], l["x"], l["y"], l["width"], l["height"],
            1 if "id" in l else 0, l.get("id", 0)))
    lc = pl["line_config_default"]
    o.append("static const mxp_line_config_t VEC_P_LINE_CONFIG_DEFAULT = {%d, %d, %d, %d, %d, %d, %d};" % (
        lc["mode"], lc["threshold"], lc["roi_pct"], lc["bands"], lc["min_width"], lc["max_width"],
        lc["color_tolerance"]))
    tc = pl["track_config_set"]
    o.append("static const mxp_track_config_t VEC_P_TRACK_CONFIG_SET = {%d, %d, %d, %d};" % (
        tc["threshold"], tc["adapt"], tc["reacquire"], tc["scale"]))
    le = pl["results_line_one"]["results"][0]["line"]
    o.append("static const mxp_line_extra_t VEC_P_LINE_EXTRA_ONE = {%s, %d};" % (
        ", ".join(str(le[k]) for k in LINE_I16), le["flags"]))
    n = pl["set_name_utf8"]
    o.append("static const mxp_set_name_t VEC_P_SET_NAME_UTF8 = {%d, %d, %d, %s};" % (
        n["function_id"], n["id"], len(n["name"].encode("utf-8")), cstr(n["name"])))
    items = pl["learned_list"]["items"]
    o.append("static const mxp_learned_t VEC_P_LEARNED_LIST[] = {")
    for it in items:
        o.append("  {%d, {%d, %d, %d}, %d, %s}," % (it["id"], *it["rgb"], len(it["name"].encode("utf-8")), cstr(it["name"])))
    o.append("};")


def main():
    src, dst = sys.argv[1], sys.argv[2]
    with open(src, encoding="utf-8") as f:
        v = json.load(f)
    o = ["/* generated by gen_vectors.py - do not edit */", ""]
    o.append("typedef struct { const char *hex; uint16_t crc; } vec_crc_t;")
    o.append("static const vec_crc_t VEC_CRC[] = {")
    for e in v["crc16"]:
        hx = e["input_ascii"].encode("ascii").hex() if "input_ascii" in e else e["input_hex"]
        o.append("  {%s, 0x%s}," % (c(hx), e["crc"]))
    o.append("};")
    o.append("typedef struct { const char *name; uint8_t cmd, seq; const char *payload_hex, *encoded_hex; } vec_frame_t;")
    o.append("static const vec_frame_t VEC_FRAMES[] = {")
    for e in v["frames"]:
        o.append("  {%s, %d, %d, %s, %s}," % (c(e["name"]), e["cmd"], e["seq"], c(e["payload_hex"]), c(e["encoded_hex"])))
    o.append("};")
    o.append("typedef struct { uint8_t cmd, seq; const char *payload_hex; } vec_expect_t;")
    o.append("typedef struct { const char *name; int nchunks; const char *chunks[8]; int nexpect; vec_expect_t expect[8]; } vec_decoder_t;")
    o.append("static const vec_decoder_t VEC_DECODER[] = {")
    for e in v["decoder"]:
        ch = ", ".join(c(x) for x in e["chunks_hex"])
        ex = ", ".join("{%d, %d, %s}" % (x["cmd"], x["seq"], c(x["payload_hex"])) for x in e["expect"])
        o.append("  {%s, %d, {%s}, %d, {%s}}," % (c(e["name"]), len(e["chunks_hex"]), ch, len(e["expect"]), ex))
    o.append("};")
    emit_payloads(v, o)
    o.append("#define VEC_COUNT(a) ((int)(sizeof(a) / sizeof((a)[0])))")
    with open(dst, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(o) + "\n")


main()
